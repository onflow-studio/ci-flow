"""The runner engine: what `ci-flow apply` renders for each managed repo.

Each managed repo gets a compose project in $CIFLOW_HOME/projects/<project>/
(default ~/.local/share/ci-flow): a runner image built from the repo's profile,
and per slot N a long-lived `dind-N` Docker daemon plus a `runner-N` service
that the runner loop starts once per job. The runner shares dind-N's network
namespace, so the fixed ports a workflow publishes never collide across slots.

The repo's profile, `.github/ci-flow.toml`, says what its jobs need. It is read
from the default branch through the GitHub API, never from a pull request.
"""
import base64
import json
import os
import shutil
import subprocess
import sys
import urllib.parse

from . import config
from .profile import CACHES, PROFILE_PATH, TOOLS, parse_profile  # noqa: F401

HOME = os.path.expanduser(os.environ.get("CIFLOW_HOME", "~/.local/share/ci-flow"))
BASE_IMAGE = "ghcr.io/actions/actions-runner:latest"
ENTRYPOINT = os.path.join(os.path.dirname(__file__), "runner", "entrypoint.sh")
UNIT_FILE = "ci-flow-runner@.service"
BASE_APT = ["xz-utils", "zstd"]



def project_dir(project, home=None):
    return os.path.join(home or HOME, "projects", project)


def image_of(project):
    return f"{project}-runner:latest"


# ── GitHub ───────────────────────────────────────────────────────────────────
def gh_api(path, method="GET", body=None, timeout=20):
    """Call the GitHub API through gh. Returns parsed JSON, or None on failure."""
    cmd = ["gh", "api", "-X", method, path]
    if body is not None:
        cmd += ["--input", "-"]
    try:
        r = subprocess.run(cmd, input=json.dumps(body) if body is not None else None,
                           capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if r.returncode != 0:
        return None
    try:
        return json.loads(r.stdout) if r.stdout.strip() else {}
    except ValueError:
        return None


class GitHub:
    """What apply needs from GitHub. Tests swap in a fake."""

    def repo(self, repo):
        return gh_api(f"repos/{repo}")

    def profile(self, repo, branch):
        """The profile's text on `branch`, or None when the repo has none."""
        data = gh_api(f"repos/{repo}/contents/{PROFILE_PATH}?ref={urllib.parse.quote(branch, safe='')}")
        if not data or data.get("encoding") != "base64":
            return None
        return base64.b64decode(data["content"]).decode()

    def fork_settings(self, repo, public):
        if public:
            return gh_api(f"repos/{repo}/actions/permissions/fork-pr-contributor-approval")
        return gh_api(f"repos/{repo}/actions/permissions/fork-pr-workflows-private-repos")


def security_warnings(repo, info, fork):
    """What a machine owner must know before running this repo's jobs here."""
    if info is None:
        return [f"{repo}: could not read the repo from GitHub; is it spelled right and is gh logged in?"]
    out = []
    if not info.get("private"):
        out.append(f"{repo} is PUBLIC: a pull request from a fork can run code on this machine. "
                   "GitHub advises against self-hosted runners on public repos.")
        policy = (fork or {}).get("approval_policy")
        if policy is None:
            out.append(f"{repo}: could not read the fork pull request approval policy; check "
                       "Settings → Actions → General → 'Approval for running fork pull request workflows'.")
        elif policy != "all_external_contributors":
            out.append(f"{repo}: fork pull requests run without approval for some contributors "
                       f"(policy {policy!r}); set it to 'Require approval for all external contributors'.")
    elif fork and fork.get("run_workflows_from_fork_pull_requests") \
            and not fork.get("require_approval_for_fork_pr_workflows"):
        out.append(f"{repo}: workflows from fork pull requests run without approval; turn on "
                   "'Require approval for fork pull request workflows'.")
    return out


# ── Rendering ────────────────────────────────────────────────────────────────
def q(s):
    """A YAML scalar: JSON strings are valid YAML."""
    return json.dumps(str(s))


def dockerfile(repo, prof, source=None):
    apt = BASE_APT + [p for p in prof["apt"] if p not in BASE_APT]
    caches = [CACHES[c] for c in prof["caches"]]
    tops = sorted({"/home/runner/" + p[len("/home/runner/"):].split("/")[0] for p in caches})
    dirs = " ".join(["/home/runner/_work", "/home/runner/externals-shared", *caches])
    owned = " ".join(["/home/runner/_work", "/home/runner/externals-shared", *tops])
    out = [
        f"# Runner image for {repo}, generated by ci-flow apply.",
        f"# Profile: {source or 'defaults'}. Edits here are overwritten.",
        f"FROM {BASE_IMAGE}",
        "",
        "USER root",
        "RUN apt-get update \\",
        f" && apt-get install -y --no-install-recommends {' '.join(apt)} \\",
        " && rm -rf /var/lib/apt/lists/*",
    ]
    for t in prof["tools"]:
        out += ["", TOOLS[t].rstrip("\n")]
    out += [
        "",
        "# Mount points for the volumes; the entrypoint chowns them again at start.",
        f"RUN mkdir -p {dirs} \\",
        f" && chown -R runner:runner {owned}",
        "",
        "COPY --chmod=755 entrypoint.sh /usr/local/bin/ci-flow-entrypoint",
        "USER runner",
        'ENTRYPOINT ["/usr/local/bin/ci-flow-entrypoint"]',
        "",
    ]
    return "\n".join(out)


def compose(entry, prof):
    project = entry["project"]
    caches = prof["caches"]
    out = [
        f"# Runners for {entry['repo']}, generated by ci-flow apply. Edits here are overwritten.",
        "#",
        "# Each slot N is a pair:",
        "#   dind-N    long-lived Docker daemon: job and service containers, image cache",
        "#   runner-N  one fresh container per job (the runner loop's `compose run --rm`),",
        "#             sharing dind-N's network namespace, so fixed service ports",
        "#             never collide across slots.",
        f"name: {project}",
        "",
        "services:",
    ]
    for n, s in entry["slots"].items():
        heap = s["node_heap"] or prof["node_heap"]
        cache_paths = " ".join(CACHES[c] for c in caches)
        out += [
            f"  dind-{n}:",
            "    image: docker:dind",
            "    privileged: true",
            "    restart: unless-stopped",
            '    command: ["dockerd", "--host=unix:///var/run/docker.sock", '
            '"--host=unix:///run/dind/docker.sock", "--group=123"]',
            f"    mem_limit: {q(s['dind_memory'])}",
            f"    cpus: {s['dind_cpus']}",
            "    # dockerd inside the container gets SERVFAIL from the embedded resolver",
            "    # for external names, so it forwards to public resolvers.",
            "    dns: [1.1.1.1, 8.8.8.8]",
            f"    networks: [runner-{n}]",
            "    volumes:",
            f"      - docker-{n}:/var/lib/docker",
            f"      - sock-{n}:/run/dind",
            f"      - work-{n}:/home/runner/_work",
            f"      - externals-{n}:/home/runner/externals",
            f"  runner-{n}:",
            f"    image: {image_of(project)}",
            '    profiles: ["runner"]',
            f"    network_mode: service:dind-{n}",
            f"    depends_on: [dind-{n}]",
            "    environment:",
            "      DOCKER_HOST: unix:///run/dind/docker.sock",
            "      # Testcontainers would otherwise use the host's gateway for mapped ports;",
            "      # they are published inside dind's network namespace instead.",
            "      TESTCONTAINERS_HOST_OVERRIDE: localhost",
            f"      CIFLOW_CACHES: {q(cache_paths)}",
        ]
        if heap:
            out.append(f"      NODE_OPTIONS: {q(f'--max-old-space-size={heap}')}")
        out += [
            f"    mem_limit: {q(s['memory'])}",
            f"    cpus: {s['cpus']}",
            "    stop_grace_period: 30s",
            "    volumes:",
            f"      - sock-{n}:/run/dind",
            f"      - work-{n}:/home/runner/_work",
            f"      - externals-{n}:/home/runner/externals-shared",
        ]
        out += [f"      - cache-{c}:{CACHES[c]}" for c in caches]
        out.append("")
    out.append("networks:")
    out += [f"  runner-{n}:" for n in entry["slots"]]
    out += ["", "volumes:"]
    for n in entry["slots"]:
        out += [f"  {v}-{n}:" for v in ("docker", "sock", "work", "externals")]
    out += [f"  cache-{c}:" for c in caches]
    out.append("")
    return "\n".join(out)


def render(entry, prof, source=None):
    """Every file of one managed repo's project directory, by name."""
    with open(ENTRYPOINT) as f:
        entrypoint = f.read()
    meta = {
        "repo": entry["repo"],
        "project": entry["project"],
        "image": image_of(entry["project"]),
        "slots": {str(n): {"labels": config.BASE_LABELS + s["labels"]} for n, s in entry["slots"].items()},
        "profile": prof,
    }
    return {
        "Dockerfile": dockerfile(entry["repo"], prof, source),
        "entrypoint.sh": entrypoint,
        "docker-compose.yml": compose(entry, prof),
        "project.json": json.dumps(meta, indent=2) + "\n",
    }


def runner_path():
    """PATH for the runner units. A systemd user session doesn't see shell-managed
    PATHs, so gh comes through mise/asdf shims when it can (survives upgrades)."""
    gh = shutil.which("gh")
    gh_dir = os.path.dirname(gh) if gh else None
    for shims in (os.path.join(os.environ.get("MISE_DATA_DIR", os.path.expanduser("~/.local/share/mise")), "shims"),
                  os.path.join(os.environ.get("ASDF_DATA_DIR", os.path.expanduser("~/.asdf")), "shims")):
        if os.access(os.path.join(shims, "gh"), os.X_OK):
            gh_dir = shims
            break
    docker = shutil.which("docker")
    parts = [gh_dir, os.path.dirname(docker) if docker else None, "/usr/local/bin", "/usr/bin", "/bin"]
    return ":".join(dict.fromkeys(p for p in parts if p))


def unit(script, python=None, home=None):
    python = python or ("/usr/bin/python3" if os.access("/usr/bin/python3", os.X_OK) else sys.executable)
    lines = [
        "# Written by ci-flow apply. Instance names are <project>-<slot>.",
        "[Unit]",
        "Description=ci-flow GitHub Actions runner %i",
        "After=network-online.target",
        "",
        "[Service]",
        "# GH_TOKEN for gh when the keyring is unreadable from a headless session.",
        "EnvironmentFile=-%h/.config/ci-flow/env",
        f"Environment=PATH={runner_path()}",
    ]
    if home and home != os.path.expanduser("~/.local/share/ci-flow"):
        lines.append(f"Environment=CIFLOW_HOME={home}")
    lines += [
        f"ExecStart={python} {script} runner-loop %i",
        "Restart=always",
        "RestartSec=10",
        # Worst case on stop: 20s to stop the runner container, 30s for the
        # loop's child to exit, then deregistration retries for up to 60s.
        "TimeoutStopSec=150",
        "",
        "[Install]",
        "WantedBy=default.target",
        "",
    ]
    return "\n".join(lines)
